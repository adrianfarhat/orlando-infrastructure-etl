"""The design workspace: discovery, feature IDs, New Feature, the feature index and checks.

Everything here works on files under designs/ only. The only other program run is a
read-only `git log` when a new ID is allocated (tools/design/ids.py), so the tool cannot
stage, commit, branch or push: created files are ordinary working-tree changes.

Rules (see designs/README.md and designs/DECISIONS.md):
- Every Markdown file under designs/features/ is a feature specification, except files in
  folders named diagrams/ or evidence/. A specification starts with YAML front matter.
- A feature's identity is its feature_id (FD-0001, ...), never its path. New IDs are one
  higher than every ID in the working tree and in the committed Git history, so a retired ID
  is never reused (T-97 P1-A, see ids.py); duplicates are reported by `check`; no command
  ever renumbers an existing feature.
- A file is never overwritten. Index files are replaced atomically.
- A feature's summary table is generated from its metadata, between the marker lines
  SUMMARY_START and SUMMARY_END. Only the lines between the two markers are ever rewritten
  (by New Feature and `index`); `check` reports a stale summary without writing anything.
- Comparisons ignore CRLF versus LF, so files that Git checked out with Windows line endings
  (core.autocrlf=true) are not reported as stale. Generated text is written with LF, or with
  the line ending the file already uses around the summary block.
"""

from __future__ import annotations

import json
import os
import posixpath
import re
import tempfile
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import quote

from ruamel.yaml import YAML
from ruamel.yaml.error import YAMLError

DESIGNS = "designs"
FEATURES = "designs/features"
INDEX = "designs/index/feature-index.md"
TEMPLATE = "designs/templates/feature-spec.md"
ARCHITECTURE = "docs/architecture"

ID_RE = re.compile(r"FD-(\d{4})\Z")
STATUSES = ("investigating", "proposed", "approved", "implementing", "verified", "deferred")
REQUIRED_KEYS = ("feature_id", "title", "design_status", "owner", "branch", "architecture_refs", "depends_on")
SECTIONS = ("## 1. Objective", "## 2. Data contract", "## 3. Logic", "## 4. Dependencies",
            "## 5. Downstream impact", "## 6. Acceptance criteria")
TABLES = {"### System components": "| Component | Relationship | Reference | Evidence status |",
          "### Related features": "| Feature | Relationship | Reference | Evidence status |"}
SUPPORT_DIRS = {"diagrams", "evidence"}          # inside a feature folder; not features
RESERVED = SUPPORT_DIRS | {"readme", "index", "templates", "features"}
WINDOWS_RESERVED = {"con", "prn", "aux", "nul", *(f"com{i}" for i in range(1, 10)), *(f"lpt{i}" for i in range(1, 10))}
MAX_NAME = 120
MAX_SLUG = 80
MAX_FILE_BYTES = 1_000_000
SUMMARY_START = ("<!-- summary:start · generated from the metadata above by New Feature and "
                 "`python -m tools.design index`; edit the metadata, not this table -->")
SUMMARY_END = "<!-- summary:end -->"
INDEX_HEADER = ("<!-- GENERATED by `python -m tools.design index` from designs/features/. "
                "Do not edit by hand: run the command again. -->")


class DesignError(Exception):
    """A usage or file problem (exit code 2)."""


@dataclass(frozen=True)
class Feature:
    path: str                     # repository-relative, "/" separated
    feature_id: str | None
    title: str | None
    status: str | None
    meta: dict = field(default_factory=dict, compare=False, repr=False)
    meta_ok: bool = field(default=False, compare=False)   # every metadata field is valid


@dataclass(frozen=True, order=True)
class Problem:
    path: str
    message: str


# --------------------------------------------------------------------------- locating

def find_root(start: Path) -> Path:
    """The repository root: the nearest folder (from start upwards) holding .git and the
    feature template."""
    start = Path(start).resolve()
    for folder in (start, *start.parents):
        if (folder / ".git").exists() and (folder / TEMPLATE).is_file():
            return folder
    raise DesignError(f"no design workspace found at or above {start} (expected .git and {TEMPLATE})")


def _rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


# --------------------------------------------------------------------------- reading

def split_front_matter(text: str) -> tuple[str | None, str]:
    """(front matter text or None, body). Front matter is between a first line '---' and
    the next line '---'."""
    if text.startswith("﻿"):
        text = text[1:]
    lines = text.split("\n")
    if not lines or lines[0].rstrip("\r") != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].rstrip("\r") == "---":
            return "\n".join(lines[1:i]), "\n".join(lines[i + 1:])
    return None, text


def _yaml() -> YAML:
    y = YAML(typ="safe", pure=True)
    return y


def read_feature(root: Path, path: Path, text: str | None = None) -> tuple[Feature, list[Problem]]:
    """A feature file's metadata and problems; `text` replaces the file's content on disk
    (an unsaved editor buffer, T-97)."""
    rel = _rel(root, path)
    problems: list[Problem] = []
    try:
        if text is None and path.stat().st_size > MAX_FILE_BYTES:
            return Feature(rel, None, None, None), [Problem(rel, f"larger than {MAX_FILE_BYTES} bytes")]
        if text is None:
            text = path.read_bytes().decode("utf-8")
        elif len(text.encode("utf-8")) > MAX_FILE_BYTES:
            return Feature(rel, None, None, None), [Problem(rel, f"larger than {MAX_FILE_BYTES} bytes")]
    except UnicodeDecodeError:
        return Feature(rel, None, None, None), [Problem(rel, "not valid UTF-8")]
    except OSError as exc:
        return Feature(rel, None, None, None), [Problem(rel, f"cannot be read ({type(exc).__name__})")]
    front, body = split_front_matter(text)
    if front is None:
        return Feature(rel, None, None, None), [Problem(rel, "no metadata block (front matter between '---' lines)")]
    try:
        meta = _yaml().load(front)
    except YAMLError as exc:
        first = str(exc).strip().splitlines()[0] if str(exc).strip() else type(exc).__name__
        return Feature(rel, None, None, None), [Problem(rel, f"metadata is not valid YAML: {first}")]
    if not isinstance(meta, dict):
        return Feature(rel, None, None, None), [Problem(rel, "metadata must be a mapping of keys to values")]
    for key in REQUIRED_KEYS:
        if key not in meta:
            problems.append(Problem(rel, f"metadata is missing {key}"))
    fid = meta.get("feature_id")
    if not (isinstance(fid, str) and ID_RE.match(fid)):
        problems.append(Problem(rel, f"feature_id must look like FD-0001, found {fid!r}"))
        fid = None
    title = meta.get("title")
    if not (isinstance(title, str) and title.strip()):
        problems.append(Problem(rel, "title must be a non-empty text"))
        title = None
    status = meta.get("design_status")
    if status not in STATUSES:
        problems.append(Problem(rel, f"design_status must be one of {', '.join(STATUSES)}, found {status!r}"))
        status = None
    for key in ("owner", "branch"):
        if key in meta and meta[key] is not None and not isinstance(meta[key], str):
            problems.append(Problem(rel, f"{key} must be text"))
    refs = meta.get("architecture_refs")
    if "architecture_refs" in meta and not (isinstance(refs, list) and all(isinstance(r, str) for r in refs)):
        problems.append(Problem(rel, "architecture_refs must be a list of repository paths"))
    problems += _check_depends_on(rel, meta.get("depends_on"), "depends_on" in meta)
    meta_ok = not problems
    problems += _check_body(rel, body)
    if meta_ok:
        problems += _check_summary(rel, text, meta)
    return Feature(rel, fid, title, status, meta, meta_ok), problems


def _check_depends_on(rel: str, value, present: bool) -> list[Problem]:
    """The format only; existence, repeats, self-dependencies and cycles are checked on the
    whole graph (dependencies.build)."""
    if not present:
        return []
    if not isinstance(value, list):
        return [Problem(rel, "depends_on must be a list of feature IDs")]
    out = []
    for i, entry in enumerate(value):
        fid = entry.get("id") if isinstance(entry, dict) else entry
        if not (isinstance(fid, str) and ID_RE.match(fid)):
            out.append(Problem(rel, f"depends_on[{i}] must be a feature ID like FD-0002 (or a mapping with id:)"))
        elif isinstance(entry, dict):
            extra = set(entry) - {"id", "optional", "condition", "note"}
            if extra:
                out.append(Problem(rel, f"depends_on[{i}] has unknown keys: {', '.join(sorted(map(str, extra)))}"))
            if "optional" in entry and not isinstance(entry["optional"], bool):
                out.append(Problem(rel, f"depends_on[{i}].optional must be true or false"))
    return out


def _check_body(rel: str, body: str) -> list[Problem]:
    lines = [line.rstrip("\r").rstrip() for line in _outside_code(body)]
    out = []
    position = -1
    for heading in SECTIONS:
        try:
            index = lines.index(heading)
        except ValueError:
            out.append(Problem(rel, f"missing section heading '{heading}'"))
            continue
        if index < position:
            out.append(Problem(rel, f"section '{heading}' is out of order"))
        position = index
    for heading, header in TABLES.items():
        if heading not in lines:
            out.append(Problem(rel, f"missing dependency table heading '{heading}'"))
            continue
        after = lines[lines.index(heading) + 1:]
        table = next((line for line in after if line.startswith("|") or line.startswith("#")), None)
        if table is None or not table.startswith("|") or table_cells(table) != table_cells(header):
            out.append(Problem(rel, f"the table under '{heading}' must have the columns {header}"))
    return out


def table_cells(row: str) -> list[str]:
    """The cells of a GFM table row, trimmed: `| a | b |`, `|a|b|` and `| a   | b |` are the same
    row (Markdown ignores the padding), so a formatter that re-aligns tables (for example Mark
    Sharp) does not break the column check. Names, order and count must still match exactly."""
    s = row.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    return [cell.strip() for cell in re.split(r"(?<!\\)\|", s)]


_FENCE_LINE = re.compile(r"\s*(`{3,}|~{3,})(.*)")


def _fence_step(line: str, fence):
    """(new fence state, is this line a fence line). A fence opens with three or more
    backticks or tildes and closes only with the same character, at least as long and with
    nothing after it (CommonMark), so a ```` fence is not closed by a ``` line inside it."""
    m = _FENCE_LINE.match(line.rstrip("\r\n"))
    if fence is None:
        if m and not (m.group(1)[0] == "`" and "`" in m.group(2)):
            return (m.group(1)[0], len(m.group(1))), True
        return None, False
    if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= fence[1] and not m.group(2).strip():
        return None, True
    return fence, False


def _outside_code(body: str) -> list[str]:
    """Body lines with fenced code blocks blanked (so headings inside code don't count)."""
    out, fence = [], None
    for line in body.split("\n"):
        inside = fence is not None
        fence, is_fence = _fence_step(line, fence)
        out.append("" if inside or is_fence else line)
    return out


def discover(root: Path, texts: dict[str, str] | None = None) -> tuple[list[Feature], list[Problem]]:
    """Every feature specification under designs/features/, in path order. `texts` maps
    repository-relative paths of existing feature files to unsaved text used instead of the
    file on disk (T-97); other paths in it are ignored."""
    base = root / FEATURES
    features, problems = [], []
    if not base.is_dir():
        return features, problems
    for folder, dirs, files in os.walk(base):
        dirs[:] = sorted(d for d in dirs if d not in SUPPORT_DIRS and not d.startswith(".")
                         and not os.path.islink(os.path.join(folder, d)))
        for name in sorted(files):
            path = Path(folder) / name
            if not name.lower().endswith(".md") or name.startswith(".") or path.is_symlink():
                continue
            feature, found = read_feature(root, path, (texts or {}).get(_rel(root, path)))
            features.append(feature)
            problems += found
    features.sort(key=lambda f: f.path)
    return features, problems


def duplicate_ids(features: list[Feature]) -> list[Problem]:
    seen: dict[str, list[str]] = {}
    for f in features:
        if f.feature_id:
            seen.setdefault(f.feature_id, []).append(f.path)
    out = []
    for fid, paths in sorted(seen.items()):
        if len(paths) > 1:
            for p in paths:
                others = ", ".join(x for x in paths if x != p)
                out.append(Problem(p, f"duplicate feature_id {fid} (also in {others})"))
    return out


def next_id(features: list[Feature], committed: set[str] | frozenset[str] = frozenset()) -> str:
    """One higher than every feature ID in `features` and in `committed` (IDs from the Git
    history, ids.committed_ids), so a retired ID is never reused."""
    from .ids import next_feature_id
    return next_feature_id([f.feature_id for f in features if f.feature_id], set(committed))


# --------------------------------------------------------------------------- names

def validate_name(name: str) -> tuple[str, str]:
    """(title, slug) for a feature name, or DesignError."""
    if not isinstance(name, str):
        raise DesignError("the feature name must be text")
    title = " ".join(name.split())
    if not title:
        raise DesignError("the feature name is empty")
    if len(title) > MAX_NAME:
        raise DesignError(f"the feature name is longer than {MAX_NAME} characters")
    if any(unicodedata.category(ch) in ("Cc", "Cf", "Cs", "Co", "Cn") for ch in name):
        raise DesignError("the feature name contains a control or invisible character")
    return title, slugify(title)


def _dashes_to_hyphens(text: str) -> str:
    """Unicode dashes (category Pd: hyphen, en and em dash, ...) and the minus sign U+2212
    become '-', so they separate words in a file name instead of being dropped."""
    return "".join("-" if unicodedata.category(ch) == "Pd" or ch == "\u2212" else ch for ch in text)


def slugify(text: str) -> str:
    ascii_text = (unicodedata.normalize("NFKD", _dashes_to_hyphens(text))
                  .encode("ascii", "ignore").decode("ascii").lower())
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text).strip("-")[:MAX_SLUG].strip("-")
    if not slug:
        raise DesignError(f"cannot make a file name from {text!r}: use letters or digits")
    if slug in RESERVED or slug in WINDOWS_RESERVED:
        raise DesignError(f"'{slug}' is a reserved name; choose another feature name")
    return slug


def _folder_segments(value: str) -> list[str]:
    path = value.replace("\\", "/").strip()
    for prefix in (FEATURES + "/", "./" + FEATURES + "/"):
        if path.startswith(prefix):
            path = path[len(prefix):]
    path = path.strip("/")
    if not path:
        raise DesignError("the parent folder is empty")
    if re.match(r"[A-Za-z]:", path) or value.strip().startswith(("/", "\\")):
        raise DesignError(f"the parent must be inside {FEATURES}/, not an absolute path: {value!r}")
    segments = path.split("/")
    for seg in segments:
        if seg in ("", ".", ".."):
            raise DesignError(f"the parent folder must stay inside {FEATURES}/: {value!r}")
    return segments


# --------------------------------------------------------------------------- New Feature

@dataclass(frozen=True)
class Created:
    path: str                     # the new specification
    feature_id: str
    moved: tuple[str, str] | None # (old, new) when a standalone parent was converted
    index: str
    refreshed: tuple[str, ...] = ()   # Related features blocks rewritten because of the move


def new_feature(root: Path, name: str, parent: str | None = None, convert_parent: bool = False) -> Created:
    root = Path(root).resolve()
    title, slug = validate_name(name)
    features, _problems = discover(root)        # other problems don't block creating a new feature
    dupes = duplicate_ids(features)
    if dupes:
        raise DesignError("duplicate feature IDs must be fixed first: " + "; ".join(p.message for p in dupes[:3]))
    lowered = title.casefold()
    for f in features:
        if f.title and " ".join(f.title.split()).casefold() == lowered:
            raise DesignError(f"a feature named {f.title!r} already exists ({f.feature_id}, {f.path})")
    template = _read_template(root)

    moved = None
    base = root / FEATURES
    parent = (parent or "").strip()
    if ID_RE.match(parent.upper()):                  # fd-0001 means FD-0001
        parent = parent.upper()
    if convert_parent and not ID_RE.match(parent):
        what = f"{parent!r} is a folder" if parent else "no parent was given"
        raise DesignError(f"--convert-parent turns a standalone parent feature into a folder, so the parent must "
                          f"be a feature ID such as FD-0003; {what}. Run again without --convert-parent")
    if not parent:
        folder = base
    elif ID_RE.match(parent):
        folder, moved = _parent_feature(root, parent, features, convert_parent)
    else:
        segments = _folder_segments(parent)
        if any(seg in SUPPORT_DIRS for seg in segments):
            raise DesignError("features cannot be created inside diagrams/ or evidence/ folders")
        folder = base.joinpath(*segments)
        if folder.exists() and not folder.is_dir():
            raise DesignError(f"the parent {_rel(root, folder)} is a file, not a folder; give its feature ID instead")
        if not folder.exists():
            for seg in _folder_segments(parent):
                if slugify(seg) != seg:
                    raise DesignError(f"a new parent folder name must be lower-case letters, digits and "
                                      f"hyphens: {seg!r} (try {slugify(seg)!r})")
    if folder.name in SUPPORT_DIRS or any(part in SUPPORT_DIRS for part in folder.relative_to(base).parts):
        raise DesignError("features cannot be created inside diagrams/ or evidence/ folders")

    target = folder / f"{slug}.md"
    if target.exists() or (folder / slug).exists():
        raise DesignError(f"{_rel(root, target)} (or a folder {slug}/) already exists; nothing was overwritten")

    from .ids import committed_ids
    feature_id = next_id(features, committed_ids(root))    # stops here, creating nothing, without full history
    text = _render(template, root, target, feature_id, title)
    front, _ = split_front_matter(text)
    text, found = apply_summary(text, _yaml().load(front), _rel(root, target))
    if found != "ok":
        raise DesignError(f"the template {TEMPLATE} needs exactly one summary block "
                          f"({SUMMARY_START[:20]}... {SUMMARY_END})")
    if moved is not None:
        _convert(root, *moved)
    folder.mkdir(parents=True, exist_ok=True)
    try:
        with open(target, "x", encoding="utf-8", newline="\n") as handle:   # never overwrites
            handle.write(text)
    except FileExistsError:
        raise DesignError(f"{_rel(root, target)} already exists; nothing was overwritten") from None
    refreshed: tuple[str, ...] = ()
    if moved is not None:                        # links to the moved parent change in the generated rows
        from . import dependencies
        refreshed = tuple(dependencies.refresh_related(root, concerning=parent))
    index = write_index(root)
    return Created(_rel(root, target), feature_id,
                   (moved[0], moved[1]) if moved else None, index, refreshed)


def _parent_feature(root: Path, fid: str, features: list[Feature], convert: bool):
    matches = [f for f in features if f.feature_id == fid]
    if not matches:
        raise DesignError(f"no feature has the ID {fid}")
    parent = root / matches[0].path
    if parent.name == "README.md":
        if convert:
            raise DesignError(f"{fid} is already a folder feature ({matches[0].path}), so there is nothing to "
                              "convert. Run again without --convert-parent")
        return parent.parent, None
    folder = parent.with_suffix("")
    if not convert:
        raise DesignError(f"{fid} is a standalone feature ({matches[0].path}), so it cannot hold subfeatures yet. "
                          f"Run again with --convert-parent to move it to {_rel(root, folder)}/README.md first "
                          "(its feature ID stays the same); nothing was changed")
    if folder.exists():
        raise DesignError(f"cannot convert {fid}: {_rel(root, folder)} already exists")
    return folder, (_rel(root, parent), _rel(root, folder / "README.md"))


def _convert(root: Path, old: str, new: str) -> None:
    """Move a standalone feature into its own folder as README.md and rewrite the relative
    links inside it so they still resolve (one level deeper)."""
    source, dest = root / old, root / new
    text = source.read_bytes().decode("utf-8")
    text = rewrite_relative_links(text, posixpath.dirname(old), posixpath.dirname(new))
    dest.parent.mkdir(parents=True, exist_ok=False)
    front, _ = split_front_matter(text)
    try:
        meta = _yaml().load(front) if front is not None else None
    except YAMLError:
        meta = None
    if isinstance(meta, dict):                    # links in the summary follow the new location
        text, _ = apply_summary(text, meta, new)
    with open(dest, "x", encoding="utf-8", newline="") as handle:
        handle.write(text)
    source.unlink()


_LINK = re.compile(r"(\]\()(<[^>]*>|[^)\s]+)((?:\s+\"[^\"]*\")?\))")


def rewrite_relative_links(text: str, old_dir: str, new_dir: str) -> str:
    """Rewrite relative Markdown link targets, outside fenced code, for a file moved from
    old_dir to new_dir (repository-relative folders). Absolute, root-relative, anchor-only
    and URL targets are left alone."""
    out, fence = [], None
    for line in text.split("\n"):
        stripped = line.lstrip()
        if fence is None and (stripped.startswith("```") or stripped.startswith("~~~")):
            fence = stripped[:3]
        elif fence is not None and stripped.startswith(fence):
            fence = None
        elif fence is None:
            line = _LINK.sub(lambda m: m.group(1) + _move_target(m.group(2), old_dir, new_dir) + m.group(3), line)
        out.append(line)
    return "\n".join(out)


def _move_target(target: str, old_dir: str, new_dir: str) -> str:
    bracketed = target.startswith("<") and target.endswith(">")
    raw = target[1:-1] if bracketed else target
    if not raw or raw.startswith(("#", "/", "\\")) or re.match(r"[A-Za-z][A-Za-z0-9+.-]*:", raw):
        return target
    path, hash_, anchor = raw.partition("#")
    if not path:
        return target
    resolved = posixpath.normpath(posixpath.join(old_dir, path))
    moved = posixpath.relpath(resolved, new_dir or ".")
    if path.endswith("/") and not moved.endswith("/"):
        moved += "/"
    result = moved + (hash_ + anchor if hash_ else "")
    return f"<{result}>" if bracketed else result


def _read_template(root: Path) -> str:
    path = root / TEMPLATE
    try:
        return path.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise DesignError(f"cannot read the template {TEMPLATE} ({type(exc).__name__})") from None


def _render(template: str, root: Path, target: Path, feature_id: str, title: str) -> str:
    here = posixpath.dirname(_rel(root, target))
    values = {
        "feature_id": feature_id,
        "title": title,
        "title_yaml": json.dumps(title, ensure_ascii=False),        # a valid YAML double-quoted string
        "architecture": posixpath.relpath(ARCHITECTURE, here),
        "designs": posixpath.relpath(DESIGNS, here),
        "templates": posixpath.relpath(DESIGNS + "/templates", here),
    }
    unknown = sorted(set(re.findall(r"\{\{(\w+)\}\}", template)) - set(values))
    if unknown:
        raise DesignError(f"the template uses unknown placeholders: {', '.join(unknown)}")
    text = re.sub(r"\{\{(\w+)\}\}", lambda m: values[m.group(1)], template)
    return text.replace("\r\n", "\n")


# --------------------------------------------------------------------------- summary

def render_summary(meta: dict, rel_path: str) -> list[str]:
    """The summary table lines (without the markers) for a feature's metadata."""
    here = posixpath.dirname(rel_path)

    def text_or(value, fallback):
        return _cell(value) if isinstance(value, str) and value.strip() else fallback

    from .links import architecture_path_problem, normal_architecture_ref     # imports this module
    links = []
    for ref in meta.get("architecture_refs") or []:
        if architecture_path_problem(ref):              # D2: never a broken link; `check` says why
            links.append(f"{_cell(ref) or '*(empty)*'} *(not a valid reference: run check)*")
            continue
        path, anchor = normal_architecture_ref(ref)
        target = _link(posixpath.relpath(path, here)) + ("#" + quote(anchor, safe="-_.~%") if anchor else "")
        links.append(f"[{_cell(ref)}]({target})")
    branch = meta.get("branch")
    return ["| Field | Value |", "|---|---|",
            f"| **Feature ID** | `{meta.get('feature_id')}` |",
            f"| **Design status** | <kbd>{meta.get('design_status')}</kbd> |",
            f"| **Owner** | {text_or(meta.get('owner'), '*not set*')} |",
            f"| **Branch** | {_code_cell(branch) if isinstance(branch, str) and branch.strip() else '*not set*'} |",
            f"| **Architecture references** | {'<br>'.join(links) if links else '*none yet*'} |"]


def _summary_span(lines: list[str]) -> tuple[str, int, int]:
    return marker_span(lines, "<!-- summary:start", SUMMARY_END)


def marker_span(lines: list[str], start_prefix: str, end_line: str) -> tuple[str, int, int]:
    """("ok", start, end) marker line indices outside fenced code, or ("missing"|
    "several"|"unclosed", -1, -1)."""
    starts, ends, fence = [], [], None
    for i, line in enumerate(lines):
        stripped = line.strip()
        inside = fence is not None
        fence, is_fence = _fence_step(line, fence)
        if inside or is_fence:
            continue
        if stripped.startswith(start_prefix) and stripped.endswith("-->"):
            starts.append(i)
        elif stripped == end_line:
            ends.append(i)
    if not starts and not ends:
        return "missing", -1, -1
    if len(starts) > 1 or len(ends) > 1:
        return "several", -1, -1
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        return "unclosed", -1, -1
    return "ok", starts[0], ends[0]


def apply_summary(text: str, meta: dict, rel_path: str) -> tuple[str, str]:
    """(new text, status). Replaces only the lines strictly between the two markers;
    everything else, including each line's own line ending, stays byte for byte."""
    lines = text.splitlines(keepends=True)
    status, start, end = _summary_span(lines)
    if status != "ok":
        return text, status
    return replace_span(lines, start, end, render_summary(meta, rel_path)), "ok"


def replace_span(lines: list[str], start: int, end: int, block: list[str]) -> str:
    """The text with the lines strictly between two marker lines replaced; every other
    line, including its own line ending, stays byte for byte."""
    newline = "\r\n" if lines[start].endswith("\r\n") else "\n"
    return "".join(lines[:start + 1] + [line + newline for line in block] + lines[end:])


def write_feature_text(path: Path, text: str) -> None:
    """Replace a feature file atomically (used only for generated blocks)."""
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".feature.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(text.encode("utf-8"))
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def _check_summary(rel: str, text: str, meta: dict) -> list[Problem]:
    new, status = apply_summary(text, meta, rel)
    if status == "missing":
        return [Problem(rel, "missing the generated summary block (the lines between "
                             "<!-- summary:start ... --> and <!-- summary:end -->)")]
    if status != "ok":
        return [Problem(rel, f"the generated summary block is {'repeated' if status == 'several' else 'not closed'}: "
                             "keep exactly one summary:start and one summary:end marker")]
    if new.replace("\r\n", "\n") != text.replace("\r\n", "\n"):
        return [Problem(rel, "the summary table is out of date with the metadata: run `python -m tools.design index`")]
    return []


def refresh_summaries(root: Path) -> list[str]:
    """Rewrite stale summary blocks of features whose metadata is valid. Files with any
    metadata problem, or without exactly one summary block, are never touched. Returns
    the repository-relative paths that were rewritten."""
    features, _ = discover(root)
    changed = []
    for f in features:
        if not f.meta_ok:
            continue
        path = root / f.path
        text = path.read_bytes().decode("utf-8")
        new, status = apply_summary(text, f.meta, f.path)
        if status != "ok" or new.replace("\r\n", "\n") == text.replace("\r\n", "\n"):
            continue
        write_feature_text(path, new)
        changed.append(f.path)
    return changed


_SPAN_WORDS = {"missing": "missing", "several": "repeated", "unclosed": "not closed"}


def not_refreshable(root: Path) -> list[Problem]:
    """One problem per feature file whose generated blocks `index` leaves alone: its
    metadata has a problem, or the markers of a block are missing, repeated or not
    closed. Nothing is read beyond what the refresh itself reads, and nothing is written."""
    from .dependencies import RELATED_END, RELATED_START          # imports this module
    from . import diagrams
    features, _ = discover(root)
    known = diagrams.sources(root)
    out = []
    for f in features:
        if not f.meta_ok:
            out.append(Problem(f.path, "its metadata has a problem, so its summary table, Related features "
                                       "rows and diagram blocks were not refreshed"))
            continue
        text = (root / f.path).read_bytes().decode("utf-8")
        lines = text.splitlines(keepends=True)
        reasons = [f"the {name} markers are {_SPAN_WORDS[status]}"
                   for name, status in (("summary table", _summary_span(lines)[0]),
                                        ("Related features", marker_span(lines, RELATED_START, RELATED_END)[0]))
                   if status != "ok"]
        if diagrams.blocking(text, f.path, known):
            reasons.append("a diagram block has a problem (see check)")
        if reasons:
            out.append(Problem(f.path, "; ".join(reasons) + ", so that block was not refreshed"
                               if len(reasons) == 1 else "; ".join(reasons) + ", so those blocks were not refreshed"))
    return out


def stale_summaries(root: Path) -> list[Problem]:
    features, problems = discover(root)
    return [p for p in problems if "summary" in p.message]


# --------------------------------------------------------------------------- index

def _cell(text: str) -> str:
    text = " ".join(str(text).split())
    return "".join("\\" + ch if ch in "\\|`*_[]<>" else ch for ch in text)


def _code_cell(text: str) -> str:
    """Text as a code span in a table cell. Backslash escapes are shown literally inside a
    code span (D1), so only '|' is escaped (GitHub tables need it, even in code) and
    backticks, which would end the span, are removed."""
    return "`" + " ".join(str(text).split()).replace("`", "").replace("|", "\\|") + "`"


def _link(path_from_index: str) -> str:
    return quote(path_from_index, safe="/-._~")


def render_index(root: Path, texts: dict[str, str] | None = None) -> str:
    """The feature index; `texts` holds unsaved feature text to use instead of the files
    on disk (T-97: the Designer computes the index before the buffers are saved)."""
    from . import dependencies, diagrams          # imports this module
    features, problems = discover(root, texts)
    graph = dependencies.build(features)
    by_folder = {posixpath.dirname(f.path): f for f in features if posixpath.basename(f.path) == "README.md"}
    rows = []
    for f in sorted((f for f in features if f.feature_id),
                    key=lambda f: (int(ID_RE.match(f.feature_id).group(1)), f.path)):
        depends_on, used_by = dependencies.index_cells(f, graph, posixpath.dirname(INDEX))
        text = (texts or {}).get(f.path)
        shown = diagrams.ids_in(text if text is not None else (root / f.path).read_bytes().decode("utf-8", "replace"))
        rows.append(f"| {f.feature_id} | {_cell(f.title or '')} | {f.status or ''} | "
                    f"{_parent_label(f, by_folder)} | {depends_on} | {used_by} | "
                    f"{', '.join(_code_cell(d) for d in shown) or '-'} | [{_cell(f.path[len(FEATURES) + 1:])}]"
                    f"({_link(posixpath.relpath(f.path, posixpath.dirname(INDEX)))}) |")
    summary = (f"Features under `designs/features/`, from their metadata. "
               f"{len(rows)} feature{'s' if len(rows) != 1 else ''}.")
    lines = [INDEX_HEADER, "", "# Feature index", "", summary, ""]
    if rows:
        lines += ["\"Depends on\" is each feature's `depends_on` list; \"Used by\" is derived from the other "
                  "features' lists. All relationships are PROPOSED. \"Diagrams\" lists the diagram IDs each "
                  "feature shows in generated diagram blocks.", "",
                  "| Feature ID | Title | Design status | Parent | Depends on | Used by | Diagrams | File |",
                  "|---|---|---|---|---|---|---|---|", *rows]
    else:
        lines.append("No features yet. Create one with New Feature (see [designs/README.md](../README.md)).")
    unindexed = sorted({p.path for p in problems} | {f.path for f in features if not f.feature_id})
    if unindexed:
        lines += ["", "## Files that need attention", "",
                  "These files under designs/features/ have problems; run `python -m tools.design check`.", ""]
        lines += [f"- [{_cell(p[len(FEATURES) + 1:])}]({_link(posixpath.relpath(p, posixpath.dirname(INDEX)))})"
                  for p in unindexed]
    return "\n".join(lines) + "\n"


def _parent_label(feature: Feature, by_folder: dict[str, Feature]) -> str:
    folder = posixpath.dirname(feature.path)
    if posixpath.basename(feature.path) == "README.md":
        folder = posixpath.dirname(folder)
    while folder != FEATURES and folder.startswith(FEATURES + "/"):
        owner = by_folder.get(folder)
        if owner is not None and owner.feature_id:
            return owner.feature_id
        if owner is None:
            return f"group {_cell(folder[len(FEATURES) + 1:])}/"
        folder = posixpath.dirname(folder)
    return "-"


def write_index(root: Path) -> str:
    return write_generated(root, INDEX, render_index(root))


def write_generated(root: Path, rel: str, text: str) -> str:
    """Replace a generated file atomically with LF text, only when its content changed
    (CRLF versus LF alone is not a change). Returns the repository-relative path."""
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and _same_text(path.read_bytes(), text):
        return _rel(root, path)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix="." + path.stem + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(text.encode("utf-8"))
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)
    return _rel(root, path)


def _same_text(data: bytes, text: str) -> bool:
    """True when the bytes are this text, with LF or CRLF line endings (a Git checkout with
    core.autocrlf=true writes CRLF)."""
    return data.replace(b"\r\n", b"\n") == text.encode("utf-8")


def index_is_fresh(root: Path) -> bool:
    path = root / INDEX
    return path.is_file() and _same_text(path.read_bytes(), render_index(root))


