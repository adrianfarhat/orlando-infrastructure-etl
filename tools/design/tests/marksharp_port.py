"""Test helper (T-95): a port of Mark Sharp 1.13.0's table exporter, so the design checks can be
tested against what Mark Sharp writes when it saves a feature specification.

Source: the extension's webview bundle (build/assets/vscode-index-*.js), class IIe, methods
exportColumnAlignedTableMarkdown (setting `alignColumns`, the default) and
exportCondensedTableMarkdown (`condensed`), plus its display-width function z$.
Verified against a real Mark Sharp buffer of a feature generated by New Feature: the port's
output is identical. Also observed there and reproduced here: a line starting with `<!--` and
the lines that follow it up to a blank line (our generated summary and Related features blocks)
are kept verbatim.
Not ported (assumption): Mark Sharp's inline serializer; each cell's Markdown is taken as is,
trimmed.

    python marksharp_port.py <file.md> <alignColumns|condensed>   -> prints the transformed file
"""
import re
import sys
import unicodedata


def width(text):                          # z$: display width (wide/fullwidth/emoji 2, combining 0)
    w = 0
    for ch in text:
        cp = ord(ch)
        if cp <= 31 or 127 <= cp <= 159 or 768 <= cp <= 879:
            continue
        if unicodedata.east_asian_width(ch) in ("W", "F") or (unicodedata.category(ch) == "So" and cp >= 0x1F000):
            w += 2
        else:
            w += 1
    return w


def split_cells(row):
    """GFM cell split on unescaped '|' (escaped pipes stay in the cell)."""
    s = row.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", s)]


def alignment(sep_cell):
    c = sep_cell.strip()
    if c.startswith(":") and c.endswith(":"):
        return "center"
    if c.startswith(":"):
        return "left"
    if c.endswith(":"):
        return "right"
    return None


def export(rows, mode):
    header, sep, *body = rows
    aligns = [alignment(c) for c in split_cells(sep)]
    cells = [split_cells(r) for r in [header] + body]
    if mode == "condensed":
        marks = {"left": ":--", "center": ":-:", "right": "--:", None: "---"}
        out = cells[:1] + [[marks[a] for a in aligns]] + cells[1:]
        return ["|" + "|".join(r) + "|" for r in out]
    cols = max(len(r) for r in cells)
    widths = [0] * cols
    for r in cells:
        for i, c in enumerate(r):
            widths[i] = max(widths[i], min(100, max(3, width(c))))
    def pad(c, i):
        # JS: c.padEnd(width - Σ(z$(ch) - 1)); padEnd counts UTF-16 code units, so a character
        # outside the BMP (for example the emoji 🔷) counts as 2 there, not 1 as in Python
        target = widths[i] - sum(width(ch) - 1 for ch in c)
        utf16 = sum(2 if ord(ch) > 0xFFFF else 1 for ch in c)
        return " " + c + " " * max(0, target - utf16) + " "
    formatted = [[pad(c, i) for i, c in enumerate(r)] for r in cells]
    seprow = []
    for i in range(cols):
        a = aligns[i] if i < len(aligns) else None
        w = widths[i]
        seprow.append({"left": " :" + "-" * (w - 1) + " ", "center": " :" + "-" * (w - 2) + ": ",
                       "right": " " + "-" * (w - 1) + ": "}.get(a, " " + "-" * w + " "))
    out = formatted[:1] + [seprow] + formatted[1:]
    return ["|" + "|".join(r) + "|" for r in out]


def transform(text, mode):
    lines = text.split("\n")
    out, i, fence = [], 0, None
    while i < len(lines):
        s = lines[i].lstrip()
        if fence is None and s.startswith(("```", "~~~")):
            fence = s[:3]; out.append(lines[i]); i += 1; continue
        if fence is not None:
            if s.startswith(fence):
                fence = None
            out.append(lines[i]); i += 1; continue
        if s.startswith("<!--"):
            # observed on a real Mark Sharp buffer: a comment line and the lines that follow it,
            # up to a blank line, are kept verbatim as one HTML block (our generated blocks)
            while i < len(lines) and lines[i].strip():
                out.append(lines[i]); i += 1
            continue
        if s.startswith("|") and i + 1 < len(lines) and re.match(r"\s*\|?\s*:?-+:?\s*(\|\s*:?-+:?\s*)*\|?\s*$", lines[i + 1]):
            j = i
            while j < len(lines) and lines[j].lstrip().startswith("|"):
                j += 1
            out.extend(export(lines[i:j], mode)); i = j; continue
        out.append(lines[i]); i += 1
    return "\n".join(out)


if __name__ == "__main__":
    path, mode = sys.argv[1], sys.argv[2]
    sys.stdout.buffer.write(transform(open(path, encoding="utf-8").read().replace("\r\n", "\n"), mode).encode("utf-8"))
