"""The architecture index: every document under docs/architecture/, its headings and its
Mermaid diagrams, generated into designs/index/architecture-index.md (T-94 Phase 2, M1).

docs/architecture/ is only read, never changed. The index is a navigation aid for designs:
it records nothing that is not in those documents, and it is regenerated, never edited.

Diagram IDs are derived from where a diagram sits, so no ID has to be written into the
current-state documents (designs/DECISIONS.md):
  <document path under docs/architecture/, without .md>/<anchor of the heading above it>
"top" stands for the heading anchor when a diagram comes before the first heading, and a
second or later diagram with the same ID gets ~2, ~3, ... An ID changes when its heading
is renamed; designs that cite the old ID are reported by the reference checks (M3).

No line numbers are recorded, so edits that do not change headings or diagrams leave the
index up to date.
"""

from __future__ import annotations

import os
import posixpath
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote

from . import markdown
from .workspace import ARCHITECTURE, MAX_FILE_BYTES, _cell, _link, _same_text, write_generated

ARCHITECTURE_INDEX = "designs/index/architecture-index.md"
ARCHITECTURE_HEADER = ("<!-- GENERATED by `python -m tools.design index` from docs/architecture/. "
                       "Do not edit by hand: run the command again. -->")
NO_TYPE = "not marked"


@dataclass(frozen=True)
class CatalogDiagram:
    diagram_id: str
    document: str                 # repository-relative path
    heading: markdown.Heading | None
    diagram_type: str | None
    source: tuple[str, ...] = ()  # the Mermaid lines between the fences (T-96 embeds copy them)
    closed: bool = True
    title: str = ""               # the document's title (its first-level heading), if any
    line: int = 0                 # 1-based line of the opening fence in the document (T-97: Edit source)


@dataclass(frozen=True)
class ArchitectureDocument:
    path: str                     # repository-relative path
    parsed: markdown.Document | None
    problem: str | None           # why it could not be read


def documents(root: Path) -> list[ArchitectureDocument]:
    """Every Markdown file under docs/architecture/ (any depth), in path order. Hidden
    files and folders and symbolic links are skipped, and so is docs/architecture/diagrams/:
    standalone diagram sources are listed under their owning document by the registry, never
    read as documents, so no diagram is counted twice (diagram library U9)."""
    base = root / ARCHITECTURE
    found = []
    if not base.is_dir():
        return found
    for folder, dirs, files in os.walk(base):
        dirs[:] = sorted(d for d in dirs if not d.startswith(".") and not os.path.islink(os.path.join(folder, d))
                         and not (Path(folder) == base and d == "diagrams"))
        for name in sorted(files):
            path = Path(folder) / name
            if not name.lower().endswith(".md") or name.startswith(".") or path.is_symlink():
                continue
            rel = path.relative_to(root).as_posix()
            try:
                if path.stat().st_size > MAX_FILE_BYTES:
                    found.append(ArchitectureDocument(rel, None, f"larger than {MAX_FILE_BYTES} bytes"))
                    continue
                text = path.read_bytes().decode("utf-8")
            except UnicodeDecodeError:
                found.append(ArchitectureDocument(rel, None, "not valid UTF-8"))
                continue
            except OSError as exc:
                found.append(ArchitectureDocument(rel, None, f"cannot be read ({type(exc).__name__})"))
                continue
            found.append(ArchitectureDocument(rel, markdown.parse(text), None))
    found.sort(key=lambda d: d.path)
    return found


def catalog(docs: list[ArchitectureDocument]) -> list[CatalogDiagram]:
    """Every Mermaid diagram, with its derived ID, in document then line order."""
    out, used = [], {}
    for doc in docs:
        if doc.parsed is None:
            continue
        stem = doc.path[len(ARCHITECTURE) + 1:]
        stem = stem[:-3] if stem.lower().endswith(".md") else stem
        heads = doc.parsed.headings
        title = heads[0].text if heads and heads[0].level == 1 else ""
        for d in doc.parsed.diagrams:
            heading = doc.parsed.headings[d.heading] if d.heading is not None else None
            base = f"{stem}/{heading.anchor if heading is not None and heading.anchor else 'top'}"
            used[base] = used.get(base, 0) + 1
            did = base if used[base] == 1 else f"{base}~{used[base]}"
            out.append(CatalogDiagram(did, doc.path, heading, d.diagram_type, d.source, d.closed, title, d.line))
    return out


def _target(doc_path: str, anchor: str = "") -> str:
    href = _link(posixpath.relpath(doc_path, posixpath.dirname(ARCHITECTURE_INDEX)))
    return href + ("#" + quote(anchor, safe="-_") if anchor else "")


def _label(heading: markdown.Heading) -> str:
    """Link text for a heading: its rendered text, escaped for a table cell or link."""
    return _cell(heading.text) or "(empty heading)"


def _registry_ids(root: Path, diagrams: list[CatalogDiagram]) -> dict[str, str]:
    """Catalog ID -> registry ID for the architecture diagrams registered in place (stage M0)."""
    from . import registry                         # imports this module lazily
    reg = registry.load(root)
    position: dict[tuple, int] = {}
    by_position = {}
    for d in diagrams:
        key = registry.catalog_key(d)
        position[key] = position.get(key, 0) + 1
        by_position[(key[0], key[1], position[key])] = d.diagram_id
    out = {}
    for e in reg.entries:
        if e.format == "mermaid-embedded" and e.status == "active":
            did = by_position.get((e.path, None if e.anchor in ("", "top") else e.anchor, e.ordinal))
            if did is not None:
                out[did] = e.diagram_id
    return out


def render_architecture_index(root: Path) -> str:
    docs = documents(root)
    diagrams = catalog(docs)
    registered = _registry_ids(root, diagrams)
    readable = [d for d in docs if d.parsed is not None]
    heading_count = sum(len(d.parsed.headings) for d in readable)
    types: dict[str, int] = {}
    for d in diagrams:
        types[d.diagram_type or NO_TYPE] = types.get(d.diagram_type or NO_TYPE, 0) + 1
    by_type = ", ".join(f"{n} {t}" for t, n in sorted(types.items()))

    lines = [ARCHITECTURE_HEADER, "", "# Architecture index", "",
             "The current-state documents in `docs/architecture/` (the verified, implemented system), with a link",
             "to every heading and every Mermaid diagram. Use it to fill a feature's \"Architecture references\";",
             "proposed designs never change these documents. See [designs/README.md](../README.md).", "",
             f"{len(docs)} document{'s' if len(docs) != 1 else ''}, {heading_count} heading"
             f"{'s' if heading_count != 1 else ''}, {len(diagrams)} diagram{'s' if len(diagrams) != 1 else ''}"
             + (f" ({by_type})." if diagrams else "."), ""]
    lines += ["## Diagrams", ""]
    if diagrams:
        lines += ["A diagram ID is the document and the anchor of the heading above the diagram. It changes when",
                  "that heading is renamed. The registry ID is the diagram's stable ID in the",
                  "[diagram registry](../diagrams/registry.yml) (see [diagram-index.md](diagram-index.md)); the diagram ID",
                  "stays valid as its alias. The type is the diagram's `%% diagram-type:` marker",
                  "([conventions.md section 2](../../docs/architecture/conventions.md#2-diagram-types)).", "",
                  "| Diagram ID | Registry ID | Type | Document | Under the heading |", "|---|---|---|---|---|"]
        for d in diagrams:
            name = d.document[len(ARCHITECTURE) + 1:]
            under = (f"[{_label(d.heading)}]({_target(d.document, d.heading.anchor)})"
                     if d.heading is not None and d.heading.anchor else "(before the first heading)")
            reg_id = f"`{registered[d.diagram_id]}`" if d.diagram_id in registered else "not registered"
            lines.append(f"| `{d.diagram_id}` | {reg_id} | "
                         f"{_cell(d.diagram_type) if d.diagram_type else '*' + NO_TYPE + '*'} | "
                         f"[{_cell(name)}]({_target(d.document)}) | {under} |")
    else:
        lines.append("No Mermaid diagrams.")
    lines += ["", "## Documents", ""]
    if not docs:
        lines.append(f"No documents in `{ARCHITECTURE}/`.")
    by_heading = {}
    for d in diagrams:
        if d.heading is not None:
            by_heading.setdefault((d.document, d.heading.line), []).append(d)
    for doc in docs:
        name = doc.path[len(ARCHITECTURE) + 1:]
        if doc.parsed is None:
            lines += [f"### {_cell(name)}", "", f"Could not be read: {doc.problem}.", ""]
            continue
        heads = list(doc.parsed.headings)
        title = heads[0].text if heads and heads[0].level == 1 else ""
        lines += [f"### [{_cell(name)}]({_target(doc.path)})" + (f": {_cell(title)}" if title else ""), ""]
        top = [d for d in diagrams if d.document == doc.path and d.heading is None]
        if top:
            lines += [f"Before the first heading: {_diagram_note(top)}", ""]
        items = heads[1:] if title else heads
        if title:
            under_title = by_heading.get((doc.path, heads[0].line))
            if under_title:
                lines += [f"Under the title: {_diagram_note(under_title)}", ""]
        if not items:
            lines += ["No headings below the title.", ""]
            continue
        shallowest = min(h.level for h in items)
        depth = -1
        for h in items:
            depth = min(h.level - shallowest, depth + 1)
            link = f"[{_label(h)}]({_target(doc.path, h.anchor)})" if h.anchor else _label(h)
            note = by_heading.get((doc.path, h.line))
            lines.append("  " * depth + f"- {link}" + (f" · {_diagram_note(note)}" if note else ""))
        lines.append("")
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def _diagram_note(items: list[CatalogDiagram]) -> str:
    return "; ".join(f"diagram `{d.diagram_id}` ({d.diagram_type or NO_TYPE})" for d in items)


def architecture_index_is_fresh(root: Path) -> bool:
    """True when the committed index matches docs/architecture/. Without a
    docs/architecture/ folder (a project that has none) there is nothing to index, so the
    index is fresh when it does not exist either."""
    path = root / ARCHITECTURE_INDEX
    if not (root / ARCHITECTURE).is_dir():
        return not path.exists()
    return path.is_file() and _same_text(path.read_bytes(), render_architecture_index(root))


def write_architecture_index(root: Path) -> str | None:
    """Write the index (only when it changed); None when there is no docs/architecture/."""
    if not (root / ARCHITECTURE).is_dir():
        return None
    return write_generated(root, ARCHITECTURE_INDEX, render_architecture_index(root))
