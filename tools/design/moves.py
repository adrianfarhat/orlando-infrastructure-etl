"""Registry moves: `registry move` and `registry adopt-moves` (T-97 PR B2b-2a S2; decisions G1-G12
in designs/DECISIONS.md; design: docs/architecture/diagram-library.md section 7.5).

Two layers (G1). These commands change only the *identity* layer: feature-owned `mermaid-md`
source files and `designs/diagrams/registry.yml`, through a recorded version 2 move transaction
(transactions.py). The generated text that shows a moved diagram (block captions and links,
diagram-index.md) is derived afterwards and separately: diagram-index.md is regenerated by the
move itself (G4), and the blocks by Feature Designer (open documents) or `refresh-blocks` (closed
documents). A refresh that fails or is refused never reverses a completed move.

- `registry move` (tool-initiated): the tooling renames the files itself, then the registry.
- `registry adopt-moves` (observed, G2): VS Code, Git or another program already renamed them;
  only the registry follows, after the identity and content at each destination are validated.

Planning is read only (`plan_move`, `plan_adopt`, `moved`): it validates the whole batch and
returns every problem, or the exact renames, the exact registry replacement and a token bound to
the plan, the source bytes, the registry bytes and the destination states. `execute` takes the
registry lock, plans again and carries the move out only when nothing is refused and the token is
unchanged. Nothing is ever overwritten; folders are created when needed and never removed (Q2).
"""

from __future__ import annotations

import dataclasses
import json
import os
import posixpath
import stat
from dataclasses import dataclass, field
from pathlib import Path

from . import registry, transactions
from .workspace import DesignError

FEATURES = "designs/features"
ARCHITECTURE = "docs/architecture"
MODES = ("move", "adopt")
_sha = transactions._sha


@dataclass
class Plan:
    mode: str
    renames: list[dict] = field(default_factory=list)     # diagram_id, from, to, via (or None), sha
    problems: list[str] = field(default_factory=list)     # any problem refuses the whole batch
    skipped: list[str] = field(default_factory=list)      # adopt-moves without arguments: reported, not adopted
    warnings: list[str] = field(default_factory=list)     # never refuse: e.g. relative links the move breaks (G6)
    before: bytes = b""                                   # the registry as read
    after: bytes = b""                                    # the registry with exactly the moved paths changed
    references: dict[str, list[str]] = field(default_factory=dict)
    token: str = ""

    def to_json(self) -> dict:
        return {"mode": self.mode, "possible": not self.problems, "problems": list(self.problems),
                "skipped": list(self.skipped), "warnings": list(self.warnings),
                "renames": [dict(r) for r in self.renames],
                "registry": {"path": registry.REGISTRY, "before_sha": _sha(self.before) if self.before else None,
                             "after_sha": _sha(self.after) if self.after and not self.problems else None},
                "references": {k: list(v) for k, v in sorted(self.references.items())},
                "token": self.token if not self.problems else ""}


# --------------------------------------------------------------------------- paths (read only)

def _norm(value, what: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise DesignError(f"{what} must be a repository path or a diagram ID")
    p = value.strip().replace("\\", "/")
    while len(p) > 1 and p.endswith("/"):
        p = p[:-1]
    return posixpath.normpath(p)


def _under(path: str, folder: str) -> bool:
    """Whether `path` is `folder` or inside it, compared ignoring letter case (G7)."""
    a, b = path.casefold(), folder.casefold()
    return a == b or a.startswith(b + "/")


def _architecture(path: str) -> bool:
    return _under(path, ARCHITECTURE)


def _kind(p: Path) -> str:
    try:
        st = os.lstat(p)
    except FileNotFoundError:
        return "absent"
    except OSError:
        return "unreadable"
    if transactions._is_link(p):
        return "link"
    return "dir" if stat.S_ISDIR(st.st_mode) else "file" if stat.S_ISREG(st.st_mode) else "other"


def _folder_problem(root: Path, rel: str) -> str:
    """Why the folders on the way to `rel` cannot be used as they are ('' when fine): a part that
    exists with other letter case (Windows would put the file in that folder under its other
    name), a part that is a file, or a link. Parts that do not exist yet are created by the move."""
    here = Path(root)
    done = []
    for part in rel.split("/")[:-1]:
        try:
            names = os.listdir(here)
        except FileNotFoundError:
            return ""
        except OSError as exc:
            return f"{'/'.join(done) or 'the repository'} cannot be listed ({exc.strerror or exc})"
        if part not in names:
            other = [n for n in names if n.casefold() == part.casefold()]
            if other:
                return (f"the folder {'/'.join(done + [part])} exists as {'/'.join(done + [other[0]])} (letter case "
                        "differs): rename the folder itself first, or choose a destination with its exact case")
            return ""
        here = here / part
        done.append(part)
        kind = _kind(here)
        if kind == "link":
            return f"{'/'.join(done)} is a symbolic link or junction (A7)"
        if kind != "dir":
            return f"{'/'.join(done)} is a file, not a folder"
    return ""


def _occupant(root: Path, rel: str) -> str:
    """What is at `rel` with any letter case ('' when nothing): its exact name, as listed."""
    parent, name = posixpath.split(rel)
    try:
        names = os.listdir(Path(root) / parent)
    except (FileNotFoundError, NotADirectoryError):
        return ""
    except OSError:
        return rel                                    # cannot be listed: treated as occupied
    for n in names:
        if n.casefold() == name.casefold():
            return posixpath.join(parent, n)
    return ""


def _dest_state(root: Path, rel: str) -> list:
    """What the token binds for a destination: every folder on the way and the entry itself."""
    here, out = Path(root), []
    for part in rel.split("/"):
        here = here / part
        out.append(_kind(here))
        if out[-1] != "dir":
            break
    return [out, _occupant(root, rel), transactions._entry_sha(root, rel) if _occupant(root, rel) else None]


_RESERVED = {"con", "prn", "aux", "nul", *(f"com{i}" for i in range(1, 10)), *(f"lpt{i}" for i in range(1, 10))}


def _name_problem(rel: str) -> str:
    """Why a destination's names cannot hold a diagram source ('' when fine): a hidden folder or
    file (never read by `check`, so the registry would name a source nobody sees; QA S2 M1) or a
    Windows reserved device name (QA S2 m1)."""
    for part in rel.split("/"):
        if part.startswith("."):
            return f"{part} is a hidden name (starting with '.'): sources there are never read by `check`"
        if part.split(".", 1)[0].rstrip(" ").casefold() in _RESERVED:
            return f"{part} is a name Windows reserves for a device"
    return ""


def _intermediate(to: str, diagram_id: str) -> str:
    """The recorded intermediate path of a case-only rename (G7): hidden, beside the destination."""
    return posixpath.join(posixpath.dirname(to), f".{diagram_id}.move.md")


# --------------------------------------------------------------------------- shared checks

class _Context:
    """Everything a plan is computed from, read once."""

    def __init__(self, root: Path, plan: Plan):
        self.root = root
        reg_path = root / registry.REGISTRY
        try:
            plan.before = reg_path.read_bytes() if reg_path.is_file() else b""
        except OSError as exc:
            plan.problems.append(f"{registry.REGISTRY} cannot be read ({exc.strerror or exc})")
        self.reg = registry.load(root)
        if not plan.before:
            plan.problems.append(f"there is no diagram registry ({registry.REGISTRY}), so there is nothing to move")
        elif self.reg.sha != _sha(plan.before):
            plan.problems.append("the registry changed while the move was planned; plan it again")
        bad = self.reg.problems + registry.identity_problems(self.reg)
        if bad:
            plan.problems.append("the registry has problems; fix them first (python -m tools.design check): "
                                 + "; ".join(p.message for p in bad[:3]))
        self.lookup = self.reg.lookup()
        self.by_path = {e.path: e for e in self.reg.entries}
        self.registered = {e.path.casefold(): e for e in self.reg.entries}
        self.files = {s.path: s for s in registry.source_files(root)}
        self.unregistered: dict[str, list[str]] = {}
        known = {e.path for e in self.reg.entries if e.format == "mermaid-md"}
        for s in self.files.values():
            if s.path not in known:
                self.unregistered.setdefault(s.diagram_id, []).append(s.path)
        self.bound: list = []                          # what the token binds beyond the renames


def _blockers(root: Path, plan: Plan) -> None:
    """Problems that refuse any move now: an unresolved or unreadable record (Q1, G9), an unresolved
    update of closed documents (its Complete is computed from the current registry) and a Git
    operation in progress (D4)."""
    _paths, bad = transactions.held(root)
    if bad:
        plan.problems.append(f"{transactions.blocker_message(root, bad)}: resolve it first "
                             f"(`python -m tools.design transaction status`) ({transactions.CODE})")
    v1 = [r.id for r in transactions.records(root) if not r.problem and not r.is_move]
    if v1:
        plan.problems.append(f"an update of closed documents is unresolved ({', '.join(v1)}): its Complete is computed "
                             "from the current registry, so no move runs until it is resolved (`python -m tools.design "
                             f"transaction status`) ({transactions.CODE})")
    busy = transactions.git_busy(root)
    if busy and busy != "index.lock":
        plan.problems.append(f"a Git operation is in progress ({busy} in the Git folder): finish or abort it first (D4)")


def _movable(e) -> str:
    """Why a registered entry is never moved by these commands ('' when it may be)."""
    if e.owner_kind != "feature":
        return (f"{e.diagram_id} is owned by {e.owner_ref}: architecture sources change only through technical-lead's "
                "documentation workflow (M1); the registry was not changed (G5)")
    if e.format != "mermaid-md":
        return f"{e.diagram_id} is {e.format}: only standalone mermaid-md sources are moved (G12)"
    if e.status != "active":
        return f"{e.diagram_id} was retired on {e.retired}: retired diagrams are never moved"
    return ""


def _write_set(rel: str, what: str) -> str:
    try:
        transactions._move_rel(rel)
    except DesignError as exc:
        return f"{what}: {exc}"
    return ""


def _links(root: Path, rel: str, what: str) -> str:
    try:
        transactions.safe_path(root, rel, feature=False)
    except DesignError as exc:
        return f"{what}: {exc} (A7)"
    return ""


def _open_problems(root: Path, plan: Plan) -> None:
    """For a tool-initiated move: no source or destination may be open in a Feature Designer window
    (D6, conservative: a window that stopped responding still counts), and every window's list must
    be readable."""
    opened, unknown = transactions.open_documents(root)
    if unknown:
        plan.problems.append(f"a Feature Designer window's list of open documents cannot be read ({', '.join(unknown)}), "
                             "so nothing is moved now; try again in a moment, or see `python -m tools.design transaction "
                             "windows`")
    for r in plan.renames:
        for p in (r["from"], r["to"], r["via"]):
            if p is not None and transactions._key(p) in opened:
                plan.problems.append(f"{p} is open in {'; '.join(opened[transactions._key(p)])}: close it first, so its "
                                     "editor cannot write it back to the old path; nothing was changed")


def _finish_plan(ctx: _Context, plan: Plan) -> Plan:
    """Batch-wide checks, the registry replacement and the token."""
    tos: dict[str, str] = {}
    froms = {r["from"].casefold(): r for r in plan.renames}
    ids: dict[str, int] = {}
    for r in plan.renames:
        ids[r["diagram_id"]] = ids.get(r["diagram_id"], 0) + 1
        key = r["to"].casefold()
        if key in tos and tos[key] != r["diagram_id"]:
            plan.problems.append(f"{r['diagram_id']} and {tos[key]} would both move to {r['to']} (destinations equal "
                                 "ignoring letter case collide on every platform, G7)")
        tos[key] = r["diagram_id"]
        other = froms.get(key)
        if other is not None and other["diagram_id"] != r["diagram_id"]:
            plan.problems.append(f"{r['to']} is the old path of {other['diagram_id']} in the same batch: chained or "
                                 "swapped moves are refused; move them in separate steps")
        if r["via"] is not None and (r["via"].casefold() in tos or r["via"].casefold() in froms):
            plan.problems.append(f"the intermediate path {r['via']} is used by another move in the batch")
    for did, n in ids.items():
        if n > 1:
            plan.problems.append(f"{did} is listed {n} times in the batch")
    if plan.renames and not plan.problems:
        try:
            doc = registry._writable(ctx.reg)
            for r in plan.renames:
                registry._find_item(doc, r["diagram_id"])["path"] = r["to"]
            text = registry.dump(doc).replace("\r\n", "\n")
            if not text.startswith("#"):
                text = registry.HEADER + text
            plan.after = text.encode("utf-8")
            why = transactions._registry_change_problem(plan.before, plan.after, plan.renames)
            if why:
                plan.problems.append(f"the registry replacement could not be computed safely ({why})")
        except DesignError as exc:
            plan.problems.append(str(exc))
    if not plan.renames and not plan.problems:
        plan.problems.append("nothing to move")
    for r in plan.renames:
        e = ctx.reg.by_id().get(r["diagram_id"])
        if e is not None:
            plan.references[r["diagram_id"]] = registry.references(ctx.root, e, ctx.reg)
        if plan.mode == "move" and posixpath.dirname(r["from"]) != posixpath.dirname(r["to"]):
            plan.warnings += _broken_links(ctx.root, r)
    plan.renames.sort(key=lambda r: r["from"])
    body = [plan.mode, [[r["diagram_id"], r["from"], r["to"], r["via"], r["sha"]] for r in plan.renames],
            _sha(plan.before) if plan.before else None, _sha(plan.after) if plan.after else None,
            [[p, _dest_state(ctx.root, p)] for r in plan.renames for p in (r["from"], r["to"], r["via"]) if p],
            ctx.bound]
    plan.token = _sha(json.dumps(body, sort_keys=True, ensure_ascii=True).encode("ascii"))[:16]
    return plan


def _broken_links(root: Path, r: dict) -> list[str]:
    """Relative links in the source that work at its old path and would not at its new one. The
    source's bytes are never changed by a move, and links are never rewritten (G6): reported only."""
    from . import links
    try:
        text = (Path(root) / r["from"]).read_bytes().decode("utf-8").replace("\r\n", "\n")
    except (OSError, UnicodeDecodeError):
        return []
    repo = links._Repo(Path(root))
    out = []
    for number, line in enumerate(links._checked_lines(text), start=1):
        for target in links._targets(line):
            if links.check_link(repo, r["from"], target) is None and links.check_link(repo, r["to"], target):
                out.append(f"{r['to']} line {number}: the relative link ({target}) will no longer resolve from the new "
                           "folder; links are never rewritten (G6): `check` reports it, fix it by hand")
    return out


# --------------------------------------------------------------------------- registry move (tool-initiated)

def _requests(requests) -> list[tuple[str, str, str | None]]:
    if not isinstance(requests, list) or not requests:
        raise DesignError("give at least one source and destination")
    if len(requests) > transactions.MAX_FILES:
        raise DesignError(f"at most {transactions.MAX_FILES} moves per batch")
    out = []
    for r in requests:
        if not (isinstance(r, (list, tuple)) and len(r) in (2, 3)):
            raise DesignError(f"a move is (source, destination[, sha256]), not {r!r}")
        want = r[2] if len(r) == 3 else None
        if want is not None and not (isinstance(want, str) and transactions.HEX64.match(want)):
            raise DesignError(f"the expected SHA-256 {want!r} is malformed")
        out.append((r[0], r[1], want))
    return out


def _expand_folder(ctx: _Context, plan: Plan, src: str, dst: str) -> list[tuple]:
    """G8 (initiating a folder move): only registered sources move, file by file, through real
    folders only; refused when the folder holds anything else that would have to move with them."""
    root = ctx.root
    if _architecture(src) or _architecture(dst):
        plan.problems.append(f"{src} -> {dst}: nothing under {ARCHITECTURE}/ is moved (G5); the registry was not "
                             "changed")
        return []
    if not (_under(src, FEATURES) and src.casefold() != FEATURES.casefold()):
        plan.problems.append(f"{src}: only folders under {FEATURES}/ can be moved")
        return []
    if not (_under(dst, FEATURES) and dst.casefold() != FEATURES.casefold()):
        plan.problems.append(f"{dst}: a folder can be moved only to a folder under {FEATURES}/")
        return []
    if _under(dst, src):
        plan.problems.append(f"{src} cannot be moved into itself ({dst})")
        return []
    if not registry._exact_case_exists(root, src):
        plan.problems.append(f"{src} does not exist with exactly this letter case")
        return []
    why = _links(root, src, src)
    if why:
        plan.problems.append(why)
        return []
    moving = [e for e in ctx.reg.entries if e.path.startswith(src + "/")]
    keep = {e.path for e in moving if _movable(e)}
    for e in moving:
        if e.path in keep:
            plan.problems.append(f"{src} holds {e.path}, which would have to move with it: {_movable(e)}")
    moving = [e for e in moving if e.path not in keep]
    paths = {e.path for e in moving}
    others, listing = [], []
    for folder, dirs, files in os.walk(root / src, followlinks=False):
        rel = Path(folder).relative_to(root).as_posix()
        for name in sorted(dirs + files):
            p = posixpath.join(rel, name)
            kind = _kind(root / p)
            listing.append([p, kind])
            if kind == "link":
                plan.problems.append(f"{src} contains a symbolic link or junction ({p}); nothing is moved through it (A7)")
            elif kind == "dir":
                if not any(q.startswith(p + "/") for q in paths):
                    others.append(p + "/")
            elif p not in paths and p not in keep:
                others.append(p)
        dirs[:] = [d for d in dirs if _kind(root / rel / d) == "dir"]
    if others:
        shown = ", ".join(sorted(others)[:8]) + (f" and {len(others) - 8} more" if len(others) > 8 else "")
        plan.problems.append(f"{src} holds files or folders that are not registered diagram sources ({shown}): a folder "
                             "move never moves, leaves behind or touches unrelated files (G8); move the sources "
                             "individually, or move those files yourself first")
    if not moving and not keep:
        plan.problems.append(f"{src} holds no registered diagram source")
    ctx.bound.append([src, sorted(listing)])
    return [(e, dst + e.path[len(src):], None) for e in sorted(moving, key=lambda x: x.path)]


def plan_move(root: Path, requests) -> Plan:
    """The validated plan for `registry move` (read only). `requests`: (source, destination[, sha])
    where a source is a diagram ID or alias, a registered source path or a folder; a destination
    is a path, or an existing folder (or one ending in /) to move the source into."""
    root = Path(root).resolve()
    plan = Plan("move")
    reqs = _requests(requests)
    ctx = _Context(root, plan)
    _blockers(root, plan)
    folders = []
    pairs = []
    for raw_src, raw_dst, want in reqs:
        src, dst = _norm(raw_src, "a source"), _norm(raw_dst, "a destination")
        try:
            transactions._clean_rel(dst)
        except DesignError as exc:
            plan.problems.append(f"destination {raw_dst!r}: {exc}")
            continue
        e = ctx.lookup.get(raw_src.strip()) or ctx.by_path.get(src)
        if e is not None:
            why = _movable(e)
            if why:
                plan.problems.append(why)
                continue
            if raw_dst.rstrip().endswith(("/", "\\")) or (_kind(root / dst) == "dir" and not dst.endswith(".md")):
                dst = posixpath.join(dst, posixpath.basename(e.path))
            pairs.append((e, dst, want))
            continue
        try:
            transactions._clean_rel(src)
            is_dir = _kind(root / src) == "dir"
        except DesignError:
            is_dir = False
        if is_dir:
            folders.append((src, dst))
            pairs += _expand_folder(ctx, plan, src, dst)
        elif _architecture(src):
            plan.problems.append(f"{src}: nothing under {ARCHITECTURE}/ is moved (G5); architecture sources change only "
                                 "through technical-lead's documentation workflow (M1)")
        else:
            plan.problems.append(f"{raw_src}: not a registered diagram ID or alias, a registered source path, or a folder "
                                 "holding registered sources")
    for i, (fa, ta) in enumerate(folders):            # overlapping folder moves in one batch
        for j, (fb, tb) in enumerate(folders):
            if i != j and (_under(ta, fb) or (i < j and (_under(fa, fb) or _under(fb, fa)))):
                plan.problems.append(f"the folder moves {fa} -> {ta} and {fb} -> {tb} overlap; move them separately")
    for e, to, want in pairs:
        _check_move(ctx, plan, e, to, want)
    if not plan.problems:
        _open_problems(root, plan)
    return _finish_plan(ctx, plan)


def _check_move(ctx: _Context, plan: Plan, e, to: str, want: str | None) -> None:
    root = ctx.root
    label = f"{e.diagram_id} ({e.path} -> {to})"
    found = [p for p in (_write_set(e.path, label), _write_set(to, label)) if p]
    if found:
        plan.problems += found
        return
    if to == e.path:
        plan.problems.append(f"{label}: it is already there")
        return
    why = _name_problem(to)
    if why:
        plan.problems.append(f"{label}: {why}")
        return
    for p in (_links(root, e.path, label), _links(root, to, label)):
        if p:
            plan.problems.append(p)
            return
    h = transactions._entry_sha(root, e.path)
    if h is None:
        plan.problems.append(f"{label}: there is no file at {e.path} with exactly this letter case: it may have been moved "
                             "already (adopt it with `python -m tools.design registry adopt-moves`) or be missing (E6/E7)")
        return
    if h == "":
        plan.problems.append(f"{label}: {e.path} is not a plain file (a folder, a link or unreadable) (A7)")
        return
    if want is not None and h != want:
        plan.problems.append(f"{label}: {e.path} changed since it was shown (its SHA-256 differs)")
        return
    s = ctx.files.get(e.path)
    if s is None or s.diagram_id != e.diagram_id or s.feature_id != e.owner_ref or s.owner_document:
        plan.problems.append(f"{label}: the front matter of {e.path} does not hold {e.diagram_id} owned by "
                             f"{e.owner_ref}; fix it first (`python -m tools.design check`, E3)")
        return
    why = _folder_problem(root, to)
    if why:
        plan.problems.append(f"{label}: {why}")
        return
    case_only = to.casefold() == e.path.casefold()
    occ = _occupant(root, to)
    if occ and not (case_only and occ == e.path):
        plan.problems.append(f"{label}: {occ} already exists; an existing file is never overwritten (A5)")
        return
    other = ctx.registered.get(to.casefold())
    if other is not None and other.diagram_id != e.diagram_id:
        plan.problems.append(f"{label}: {to} is the registered path of {other.diagram_id} (A5)")
        return
    via = None
    if case_only:
        via = _intermediate(to, e.diagram_id)
        if _occupant(root, via):
            plan.problems.append(f"{label}: the intermediate path {via} already exists; remove it first")
            return
    plan.renames.append({"diagram_id": e.diagram_id, "from": e.path, "to": to, "via": via, "sha": h})


# --------------------------------------------------------------------------- adopt-moves (observed)

def _check_adopt(ctx: _Context, e, to: str, want: str | None) -> tuple[dict | None, str]:
    """(the observed rename, '') when `to` is where `e`'s source now is, with its identity and a
    well-formed source; (None, why) otherwise."""
    from . import diagrams
    root = ctx.root
    label = f"{e.diagram_id} ({e.path} -> {to})"
    why = _movable(e) or _write_set(e.path, label) or _write_set(to, label) or _links(root, to, label)
    if why:
        return None, why
    if _name_problem(to):
        return None, f"{label}: {_name_problem(to)}"
    if to == e.path:
        return None, f"{label}: it is already registered there"
    old = transactions._entry_sha(root, e.path)
    if old is not None:
        return None, (f"{label}: {e.path} still exists, so nothing was moved there to adopt (a copy is not a move, E4)"
                      if old else f"{label}: something that is not a plain file is at {e.path}")
    h = transactions._entry_sha(root, to)
    if h is None:
        return None, f"{label}: there is no file at {to} with exactly this letter case"
    if h == "":
        return None, f"{label}: {to} is not a plain file (a folder, a link or unreadable) (A7)"
    if want is not None and h != want:
        return None, f"{label}: {to} does not have the content it had before the rename (its SHA-256 differs)"
    s = ctx.files.get(to)
    if s is None or s.diagram_id != e.diagram_id:
        return None, f"{label}: {to} does not hold {e.diagram_id} in its front matter (E3); nothing is guessed"
    if s.feature_id != e.owner_ref or s.owner_document:
        return None, (f"{label}: {to} names the owner {s.feature_id or s.owner_document or '(none)'}, but the registry's "
                      f"owner of {e.diagram_id} is {e.owner_ref}; a move never changes the owner (E3)")
    src = diagrams._refuse_markers(diagrams._registered_source(root, dataclasses.replace(e, path=to)))
    if src.problem or not src.closed:
        return None, f"{label}: {to} is not a well-formed mermaid-md source ({src.problem or 'its Mermaid block is not closed'})"
    other = ctx.registered.get(to.casefold())
    if other is not None and other.diagram_id != e.diagram_id:
        return None, f"{label}: {to} is the registered path of {other.diagram_id} (A5)"
    cands = sorted(ctx.unregistered.get(e.diagram_id, []))
    if len(cands) > 1:
        return None, (f"{e.diagram_id} is at {len(cands)} unregistered paths ({', '.join(cands)}): nothing is guessed; "
                      "keep one of them (A8)")
    return {"diagram_id": e.diagram_id, "from": e.path, "to": to, "via": None, "sha": h}, ""


def moved(root: Path) -> dict:
    """Every registered, active `mermaid-md` source that is missing at its registered path (E6/E7),
    with what is found instead. Read only.

    matches: exactly one unregistered file holds the ID (`problem` '' when it can be adopted);
    ambiguous: the ID is at two or more unregistered paths (nothing is guessed);
    missing: no file holds the ID (E7, never relinked automatically);
    architecture: document-owned sources (G5: technical-lead's documentation workflow)."""
    root = Path(root).resolve()
    plan = Plan("adopt")
    ctx = _Context(root, plan)
    out = {"matches": [], "ambiguous": [], "missing": [], "architecture": [], "registry_sha": ctx.reg.sha}
    for e in ctx.reg.entries:
        if e.status != "active" or e.format != "mermaid-md" or registry._exact_case_exists(root, e.path):
            continue
        cands = sorted(ctx.unregistered.get(e.diagram_id, []))
        item = {"diagram_id": e.diagram_id, "from": e.path, "candidates": cands, "owner": e.owner_ref}
        if e.owner_kind != "feature":
            out["architecture"].append({**item, "problem": _movable(e)})
        elif len(cands) > 1:
            out["ambiguous"].append({**item, "problem": f"{e.diagram_id} is at {len(cands)} unregistered paths: nothing "
                                                        "is guessed; keep one of them"})
        elif not cands:
            out["missing"].append({**item, "problem": f"{e.diagram_id}'s source {e.path} does not exist and no file holds "
                                                      "its ID (E7): never relinked automatically"})
        else:
            rename, why = _check_adopt(ctx, e, cands[0], None)
            out["matches"].append({**item, "to": cands[0], "sha": rename["sha"] if rename else None, "problem": why})
    return out


def plan_adopt(root: Path, requests=None) -> Plan:
    """The validated plan for `registry adopt-moves` (read only). `requests`: (old, new[, sha]) where
    old is a registered path, ID or alias, or a folder whose registered sources were all renamed into
    new; None: every adoptable E6 match (the rest is listed in `skipped`)."""
    root = Path(root).resolve()
    plan = Plan("adopt")
    ctx = _Context(root, plan)
    _blockers(root, plan)
    if requests is None:
        found = moved(root)
        pairs = []
        for m in found["matches"]:
            if m["problem"]:
                plan.skipped.append(m["problem"])
            else:
                pairs.append((ctx.reg.by_id()[m["diagram_id"]], m["to"], None))
        plan.skipped += [x["problem"] + f" ({x['from']}" + (f"; candidates {', '.join(x['candidates'])})" if x["candidates"]
                                                             else ")") for k in ("ambiguous", "missing", "architecture")
                         for x in found[k]]
        if not pairs and not plan.problems:
            plan.problems.append("no moved source can be adopted" + (": " + "; ".join(plan.skipped) if plan.skipped else
                                                                    " (every registered source is at its path)"))
    else:
        pairs = []
        for raw_old, raw_new, want in _requests(requests):
            old, new = _norm(raw_old, "--from"), _norm(raw_new, "--to")
            try:
                transactions._clean_rel(new)
            except DesignError as exc:
                plan.problems.append(f"--to {raw_new!r}: {exc}")
                continue
            e = ctx.lookup.get(raw_old.strip()) or ctx.by_path.get(old)
            if e is not None:
                if _kind(root / new) == "dir" and not new.endswith(".md"):
                    new = posixpath.join(new, posixpath.basename(e.path))
                pairs.append((e, new, want))
                continue
            under = [x for x in ctx.reg.entries if x.path.startswith(old + "/")]
            if _architecture(old) or _architecture(new):
                plan.problems.append(f"{old} -> {new}: nothing under {ARCHITECTURE}/ is adopted (G5); technical-lead "
                                     "relinks architecture sources through the documentation workflow (M1)")
            elif not under:
                plan.problems.append(f"{raw_old}: not a registered diagram ID, alias or path, or a folder that held "
                                     "registered sources")
            elif _under(new, old):
                plan.problems.append(f"{old} cannot have been moved into itself ({new})")
            else:                                     # G8 (adopting a folder rename the user made): only the registry
                for x in sorted(under, key=lambda y: y.path):
                    if x.status != "active":
                        plan.skipped.append(f"{x.diagram_id} ({x.path}) was retired: it is not adopted")
                        continue
                    pairs.append((x, new + x.path[len(old):], want if len(under) == 1 else None))
        if not pairs and not plan.problems:
            plan.problems.append("nothing to adopt")
    for e, to, want in pairs:
        rename, why = _check_adopt(ctx, e, to, want)
        if why:
            plan.problems.append(why)
        else:
            plan.renames.append(rename)
    return _finish_plan(ctx, plan)


# --------------------------------------------------------------------------- carrying it out

def plan(root: Path, mode: str, requests) -> Plan:
    if mode not in MODES:
        raise DesignError(f"the mode must be move or adopt, not {mode!r}")
    return plan_move(root, requests) if mode == "move" else plan_adopt(root, requests)


def refused(p: Plan) -> str:
    return "nothing was changed:\n" + "\n".join(f"  - {x}" for x in p.problems)


def execute(root: Path, mode: str, requests, token: str) -> dict:
    """Carry out exactly the plan that was shown (`token`): under the registry lock, refused while a
    Git operation is in progress, planned and validated again, then one recorded move transaction
    (transactions.prepare_move and commit_move). The generated text is not part of it (G1)."""
    root = Path(root).resolve()
    if not isinstance(token, str) or not token:
        raise DesignError("give the token the plan printed (--confirm TOKEN)")
    with registry.lock(root):
        transactions._fault(root, "moves-after-lock")
        transactions._git_ready(root)
        transactions._remove_debris(root)             # a finished record whose removal was interrupted
        transactions.registry_guard(root)
        again = plan(root, mode, requests)
        if again.problems:
            raise DesignError(refused(again))
        if again.token != token:
            raise DesignError("a source, the registry or a destination changed since the move was planned; nothing was "
                              "changed. Plan it again (without --confirm) and check what it shows now")
        transactions._fault(root, "moves-before-prepare")
        rec = transactions.prepare_move(root, mode, again.renames, again.before, again.after)
        try:                                          # once more, just before anything outside the record changes
            transactions._git_ready(root)
            if transactions._registry_sha(root) != _sha(again.before):
                raise DesignError("the registry changed while the move was prepared")
            for r in again.renames:
                if transactions._entry_sha(root, r["to" if mode == "adopt" else "from"]) != r["sha"]:
                    raise DesignError(f"{r['to' if mode == 'adopt' else 'from']} changed while the move was prepared")
        except DesignError as exc:
            cleanup = transactions._finish_safely(root, rec)   # nothing outside the record was touched
            raise DesignError(f"{exc}; nothing was changed"
                              + (f"; {transactions.cleanup_warning(rec, cleanup, 'abandon')}" if cleanup else "")) from None
        result = transactions.commit_move(root, rec)
    result.update(mode=mode, references={k: len(v) for k, v in again.references.items()})
    result["refresh"] = _layer_two(root, [r["diagram_id"] for r in again.renames])
    return result


def _layer_two(root: Path, ids: list[str]) -> dict:
    """What shows the moved diagrams and is now out of date (G1: refreshed separately; never part of,
    and never able to reverse, the move). Best effort and read only."""
    try:
        found = transactions.affected(root)
    except Exception as exc:                          # the move is complete either way
        return {"documents": [], "problem": f"{type(exc).__name__}: {exc}"[:300]}
    docs = [d for d in found["documents"] if set(d["blocks"]) & set(ids)]
    return {"documents": docs, "sources_token": found["sources_token"], "problem": ""}
